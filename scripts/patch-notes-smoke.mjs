import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox','--disable-dev-shm-usage','--single-process','--no-zygote','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:280,height:653},isMobile:true,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.BASE_URL||'http://127.0.0.1:5173';
try {
  await page.goto(base+'/?advenced');
  assert.match(await page.locator('body').innerText(),/v0\.62/i,'advanced home shows v0.62');
  assert.doesNotMatch(await page.locator('body').innerText(),/v0\.63/i);
  await page.getByRole('button',{name:'PATCH NOTES'}).tap();
  const dialog=page.getByRole('dialog',{name:'PATCH NOTES'});
  const version=dialog.locator('.relative.mb-3').getByText('v0.62',{exact:true});
  assert.equal(await version.count(),1,'all changes appear in one v0.62 entry');
  assert.doesNotMatch(await dialog.innerText(),/0\.63/,'the extra updates must not look like a new release');
  assert.match(await dialog.locator('h3').innerText(),/v0\.62/,'current heading uses the same version');
  assert.equal(await dialog.getByText('v0.61',{exact:true}).count(),1,'previous version follows naturally');
  const entry=version.locator('..').locator('..');
  const text=await entry.innerText();
  assert.match(text,/CURRENT/); assert.match(text,/650 damage/); assert.match(text,/opposing side/); assert.match(text,/reward chest/); assert.match(text,/UI Doctor/);
  assert.match(text,/whole interface has a fresh field-lab look/); assert.match(text,/zoom the battlefield drawer in or out/); assert.match(text,/Colony health and the round map now have dedicated space/);
  assert.match(text,/main menu feels softer and more natural/); assert.match(text,/roar cue and label are smaller/);
  assert.match(text,/Auto, Low, Medium or High 3D resolution/); assert.match(text,/UI Doctor reports the active render size/);
  assert.match(text,/Fixed close-zoom framing in fullscreen/); assert.match(text,/Sideways mode puts the drawer beside/);
  assert.match(text,/cropped battlefield/); assert.match(text,/FIT button/); assert.match(text,/swipeable colony ladder/); assert.match(text,/scrollable bench\/supply dock/); assert.match(text,/clipped drawer frame/);
  assert.match(text,/straight push-in/); assert.match(text,/no longer tilts the battlefield/); assert.match(text,/keeps its label inside its border/);
  assert.equal(await entry.locator('li').count(),20,'the single v0.62 entry retains all 19 notes and adds the untilted zoom toolbar fix');
  for (const width of [280,320,390]) {
    await page.setViewportSize({width,height:653});
    const layout=await version.evaluate(el=>{
      const header=el.parentElement, r=header.getBoundingClientRect();
      return {scroll:header.scrollWidth,client:header.clientWidth,left:r.left,right:r.right,children:[...header.children].map(x=>x.getBoundingClientRect().toJSON())};
    });
    assert.ok(layout.left>=0&&layout.right<=width&&layout.scroll<=layout.client+1,`merged heading must fit ${width}px: ${JSON.stringify(layout)}`);
    assert.ok(layout.children.every(c=>c.left>=layout.left-1&&c.right<=layout.right+1),`heading labels must fit ${width}px`);
  }
  await page.evaluate(()=>localStorage.setItem('smartbugs.settings',JSON.stringify({rev:2,lang:'id',motion:'full',potato:false,background:'dark'})));
  await page.reload();
  await page.getByRole('button',{name:'CATATAN PEMBARUAN'}).tap();
  const indonesian=page.getByRole('dialog',{name:'CATATAN PEMBARUAN'});
  const merged=indonesian.locator('.relative.mb-3').getByText('v0.62',{exact:true}).locator('..').locator('..');
  const translated=await merged.innerText();
  assert.match(translated,/Laba-laba menghadap lurus ke sisi lawan/,'gameplay correction is translated');
  assert.match(translated,/Peti VS/,'chest update remains translated');
  assert.match(translated,/Menu utama terasa lebih lembut dan alami/,'compact menu update is translated');
  assert.match(translated,/label raungan Laba-laba kini lebih kecil/,'smaller roar cue is translated');
  assert.match(translated,/memperbesar atau memperkecil laci pertempuran/,'drawer zoom note is translated');
  assert.match(translated,/Pilih resolusi 3D Otomatis, Rendah, Sedang, atau Tinggi/,'resolution note is translated');
  assert.match(translated,/Perbaikan tampilan zoom dekat di layar penuh/,'zoom fix is translated');
  assert.match(translated,/Mode menyamping menempatkan laci/,'sideways mode is translated');
  assert.match(translated,/Perbaikan medan tempur terpotong/,'drawer fit fix is translated');
  assert.match(translated,/tombol PAS/,'FIT toolbar note is translated');
  assert.match(translated,/satu baris tangga koloni yang dapat digeser/,'portrait ladder note is translated');
  assert.match(translated,/dok bangku\/toko yang dapat digulir/,'sideways dock note is translated');
  assert.match(translated,/bingkai laci terpotong/,'Doctor drawer audit note is translated');
  assert.match(translated,/mendorong kamera lurus/,'untilted zoom note is translated');
  assert.match(translated,/labelnya tetap di dalam bingkainya/,'FIT label note is translated');
  assert.deepEqual(errors,[]);
  console.log('PASS single v0.62 patch notes: 20 retained and extra updates, translations and narrow layouts');
} finally {await browser.close();}
