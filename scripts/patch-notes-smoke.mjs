import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH,args:['--no-sandbox','--disable-dev-shm-usage','--single-process','--no-zygote','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:280,height:653},isMobile:true,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.BASE_URL||'http://127.0.0.1:5173';
try {
  await page.goto(base+'/?advenced');
  assert.match(await page.locator('body').innerText(),/v0\.63/i,'advanced home shows v0.63');
  assert.doesNotMatch(await page.locator('body').innerText(),/v0\.64/i);
  await page.getByRole('button',{name:'PATCH NOTES'}).tap();
  const dialog=page.getByRole('dialog',{name:'PATCH NOTES'});
  const version=dialog.locator('.relative.mb-3').getByText('v0.63',{exact:true});
  assert.equal(await version.count(),1,'all changes appear in one v0.63 entry');
  assert.doesNotMatch(await dialog.innerText(),/0\.64/,'the patch must not look like a skipped release');
  assert.match(await dialog.locator('h3').innerText(),/v0\.63/,'current heading uses the same version');
  assert.equal(await dialog.getByText('v0.62',{exact:true}).count(),1,'previous version follows naturally');
  const entry=version.locator('..').locator('..');
  const text=await entry.innerText();
  assert.match(text,/CURRENT/); assert.match(text,/cropped battlefield/); assert.match(text,/FIT button/); assert.match(text,/swipeable colony ladder/); assert.match(text,/scrollable bench\/supply dock/); assert.match(text,/clipped drawer frame/);
  assert.equal(await entry.locator('li').count(),5,'current entry lists the drawer and responsiveness fixes');
  const previous=dialog.locator('.relative.mb-3').getByText('v0.62',{exact:true}).locator('..').locator('..');
  const prevText=await previous.innerText();
  assert.match(prevText,/650 damage/); assert.match(prevText,/opposing side/); assert.match(prevText,/reward chest/); assert.match(prevText,/UI Doctor/);
  assert.match(prevText,/whole interface has a fresh field-lab look/); assert.match(prevText,/zoom the battlefield drawer in or out/); assert.match(prevText,/Colony health and the round map now have dedicated space/);
  assert.match(prevText,/main menu feels softer and more natural/); assert.match(prevText,/roar cue and label are smaller/);
  assert.match(prevText,/Auto, Low, Medium or High 3D resolution/); assert.match(prevText,/UI Doctor reports the active render size/);
  assert.match(prevText,/Fixed close-zoom framing in fullscreen/); assert.match(prevText,/Sideways mode puts the drawer beside/);
  assert.equal(await previous.locator('li').count(),14,'previous entry retains the gameplay and UI changes');
  for (const width of [280,320,390]) {
    await page.setViewportSize({width,height:653});
    const layout=await version.evaluate(el=>{
      const header=el.parentElement, r=header.getBoundingClientRect();
      return {scroll:header.scrollWidth,client:header.clientWidth,left:r.left,right:r.right,children:[...header.children].map(x=>x.getBoundingClientRect().toJSON())};
    });
    assert.ok(layout.left>=0&&layout.right<=width&&layout.scroll<=layout.client+1,`merged heading must fit ${width}px: ${JSON.stringify(layout)}`);
    assert.ok(layout.children.every(c=>c.left>=layout.left-1&&c.right<=layout.right+1),`heading labels must fit ${width}px`);
  }
  await page.evaluate(()=>localStorage.setItem('smartbugs.settings',JSON.stringify({rev:2,lang:'id',motion:'full',potato:false,background:'dark'})));
  await page.reload();
  await page.getByRole('button',{name:'CATATAN PEMBARUAN'}).tap();
  const indonesian=page.getByRole('dialog',{name:'CATATAN PEMBARUAN'});
  const merged=indonesian.locator('.relative.mb-3').getByText('v0.63',{exact:true}).locator('..').locator('..');
  assert.match(await merged.innerText(),/Perbaikan medan tempur terpotong/,'drawer fit fix is translated');
  assert.match(await merged.innerText(),/tombol PAS/,'FIT toolbar note is translated');
  assert.match(await merged.innerText(),/satu baris tangga koloni yang dapat digeser/,'portrait ladder note is translated');
  assert.match(await merged.innerText(),/dok bangku\/toko yang dapat digulir/,'sideways dock note is translated');
  assert.match(await merged.innerText(),/bingkai laci terpotong/,'Doctor drawer audit note is translated');
  const prevId=indonesian.locator('.relative.mb-3').getByText('v0.62',{exact:true}).locator('..').locator('..');
  assert.match(await prevId.innerText(),/Laba-laba menghadap lurus ke sisi lawan/,'previous correction remains translated');
  assert.match(await prevId.innerText(),/Peti VS/,'chest update remains translated');
  assert.match(await prevId.innerText(),/Menu utama terasa lebih lembut dan alami/,'compact menu update is translated');
  assert.match(await prevId.innerText(),/label raungan Laba-laba kini lebih kecil/,'smaller roar cue is translated');
  assert.match(await prevId.innerText(),/memperbesar atau memperkecil laci pertempuran/,'drawer zoom note is translated');
  assert.match(await prevId.innerText(),/Pilih resolusi 3D Otomatis, Rendah, Sedang, atau Tinggi/,'resolution note is translated');
  assert.match(await prevId.innerText(),/Perbaikan tampilan zoom dekat di layar penuh/,'zoom fix is translated');
  assert.match(await prevId.innerText(),/Mode menyamping menempatkan laci/,'sideways mode is translated');
  assert.deepEqual(errors,[]);
  console.log('PASS v0.63 patch notes, retained v0.62 changes, translations and narrow layouts');
} finally {await browser.close();}
