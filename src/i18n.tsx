const SettingsCtx = createContext<Ctx | null>(null);
const KEY = "smartbugs.settings";

function load(): Settings {
  try {
    const raw = localStorage.getItem(KEY);
    if (raw) {
      const parsed = JSON.parse(raw) as Partial<Settings>;
      if (parsed.lang === "id" || parsed.lang === "en") {
        return {
          lang: parsed.lang,
          motion: parsed.motion === "reduced" ? "reduced" : "full",
          potato: parsed.potato === true,
        };
      }
    }
  } catch {
    /* storage may be unavailable */
  }
  return { lang: "en", motion: "full", potato: false };
}

/** Pure lookup so translation can be tested without mounting React. */
export function translate(en: string, lang: Lang): string {
  return lang === "id" ? ID[en] ?? en : en;
}

export function fill(template: string, vars: Record<string, string | number>): string {
  let out = template;
  for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}

export function hasTranslation(en: string): boolean {
  return Object.prototype.hasOwnProperty.call(ID, en);
}

export function SettingsProvider({ children }: { children: React.ReactNode }) {
  const [settings, setSettings] = useState<Settings>(load);

  useEffect(() => {
    try {
      localStorage.setItem(KEY, JSON.stringify(settings));
    } catch {
      /* ignore */
    }
    document.documentElement.lang = settings.lang === "id" ? "id" : "en";
    document.documentElement.dataset.motion = settings.motion;
    document.documentElement.dataset.potato = settings.potato ? "1" : "0";
    // Scene3D re-reads heavy renderer settings on this signal.
    window.dispatchEvent(new CustomEvent("sb-potato"));
  }, [settings]);

  const setLang = useCallback((lang: Lang) => setSettings((s) => ({ ...s, lang })), []);
  const setMotion = useCallback(
    (motion: Settings["motion"]) => setSettings((s) => ({ ...s, motion })),
    [],
  );
  const setPotato = useCallback((potato: boolean) => setSettings((s) => ({ ...s, potato })), []);
  const reset = useCallback(() => setSettings({ lang: "en", motion: "full", potato: false }), []);

  const value = useMemo<Ctx>(() => {
    const lang = settings.lang;
    return {
      ...settings,
      setLang,
      setMotion,
      setPotato,
      reset,
      t: (en: string) => translate(en, lang),
    };
  }, [settings, setLang, setMotion, reset]);

  return <SettingsCtx.Provider value={value}>{children}</SettingsCtx.Provider>;
}

/**
 * Falls back to an English, full-motion context when no provider is mounted.
 * That keeps component-level rendering and tests usable in isolation instead
 * of throwing on a missing provider.
 */
const FALLBACK: Ctx = {
  lang: "en",
  motion: "full",
  potato: false,
  setLang: () => {},
  setMotion: () => {},
  setPotato: () => {},
  reset: () => {},
  t: (en: string) => en,
};

export function useSettings(): Ctx {
  return useContext(SettingsCtx) ?? FALLBACK;
}
